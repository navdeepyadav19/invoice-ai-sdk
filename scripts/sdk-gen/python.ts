function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  console.log(`  wrote ${path.slice(ROOT.length + 1)}`)
}

const resourcesDir = join(SRC, 'resources')
mkdirSync(resourcesDir, { recursive: true })
for (const f of readdirSync(resourcesDir)) {
  if (f.endsWith('.py')) rmSync(join(resourcesDir, f))
}

const resourceModules: { resource: SpecResource; module: string; cls: string }[] = []
for (const resource of spec.resources) {
  const ops = spec.operations.filter((o) => o.resource === resource)
  write(join(resourcesDir, `${resource.snake}.py`), emitResource(resource, ops))
  resourceModules.push({ resource, module: resource.snake, cls: className(resource) })
}

