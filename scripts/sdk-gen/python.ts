/** Constraints are the server's to enforce; the SDK parses leniently so new values never break old clients. */
const STRIP = new Set([
  'pattern',
  'minLength',
  'maxLength',
  'minimum',
  'maximum',
  'exclusiveMinimum',
  'exclusiveMaximum',
  'minItems',
  'maxItems',
  'format',
  'examples',
  'example',
  'propertyNames',
])

function lenient(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(lenient)
  if (!node || typeof node !== 'object') return node
  const out: Json = {}
  for (const [k, v] of Object.entries(node as Json)) {
    if (STRIP.has(k)) continue
    if (k === 'additionalProperties' && v === false) continue
    out[k] = k === 'properties' ? Object.fromEntries(Object.entries(v as Json).map(([pk, pv]) => [pk, lenient(pv)])) : lenient(v)
  }
  return out
}

function generateModels(): void {
  const uv = spawnSync('uv', ['--version'], { encoding: 'utf8' })
  if (uv.status !== 0) {
    console.warn('  ! uv not found: skipped invoice_ai/types/_generated.py (install uv to regenerate the Python models)')
    return
  }
  const dir = mkdtempSync(join(tmpdir(), 'invoice-ai-sdk-gen-'))
  const input = join(dir, 'schemas.json')
  const doc = {
    openapi: '3.1.0',
    info: { title: spec.title, version: spec.version },
    paths: {},
    components: { schemas: lenient(schemas) },
  }
  writeFileSync(input, JSON.stringify(doc, null, 2))
  const out = join(SRC, 'types', '_generated.py')
  const args = [
    'run',
    '--project',
    PKG,
    '--frozen',
    '--quiet',
    'datamodel-codegen',
    '--input',
    input,
    '--input-file-type',
    'openapi',
    '--output',
    out,
    '--output-model-type',
    'pydantic_v2.BaseModel',
    '--base-class',
    'invoice_ai._models.BaseModel',
    '--target-python-version',
    '3.9',
    '--enum-field-as-literal',
    'all',
    '--use-schema-description',
    '--use-field-description',
    '--use-double-quotes',
    '--keep-model-order',
    '--disable-timestamp',
    '--formatters',
    'ruff-format',
    '--custom-file-header',
    `${HEADER.trim()}\n# Models by datamodel-code-generator; constraints are stripped so parsing stays lenient.`,
  ]
  const res = spawnSync('uv', args, { cwd: PKG, encoding: 'utf8' })
  rmSync(dir, { recursive: true, force: true })
  if (res.status !== 0) {
    console.error(res.stdout, res.stderr)
    throw new Error('sdk-gen: datamodel-codegen failed')
  }
  console.log(`  wrote ${out.slice(ROOT.length + 1)}`)
}

