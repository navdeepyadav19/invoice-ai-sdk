/**
 * Generates the Python SDK (packages/sdk-python) from api-docs/openapi.json.
 *
 *   pnpm sdk:gen        (runs ts.ts, then this)
 *
 * Writes, under packages/sdk-python/invoice_ai:
 *   types/_generated.py   Pydantic v2 models, by datamodel-code-generator (needs `uv`)
 *   types/params.py       TypedDicts for nested request objects (InvoiceLineInputParam…)
 *   types/__init__.py     public re-exports
 *   resources/<name>.py   one sync + one async class per tag, plus their .with_raw_response views
 *   resources/__init__.py re-exports and the resource-carrying client bases
 *   _operations.py        operationId → resource.method manifest (tests use it)
 *   _meta.py              API version from info.version
 *
 * Model generation runs datamodel-code-generator through `uv run` in the
 * package's own environment (pinned in uv.lock). Without uv it is skipped with
 * a warning, and everything else is still regenerated.
 *
 * Never edit those files by hand; change the spec or this script and rerun.
 */
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deref, loadSpec, refName, type Json, type SpecOperation, type SpecResource } from './spec'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SPEC = join(ROOT, 'api-docs', 'openapi.json')
const PKG = join(ROOT, 'packages', 'sdk-python')
const SRC = join(PKG, 'invoice_ai')
const HEADER = '# Generated by scripts/sdk-gen/python.ts from api-docs/openapi.json. Do not edit.\n'

const spec = loadSpec(SPEC)
const raw = spec.raw

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)
const pascalWords = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map(pascal).join('')
const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()
const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v)) as T

const PY_KEYWORDS = new Set(
  'False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield'.split(
    ' ',
  ),
)
/** Keyword-only request options every method takes; spec params may not collide with them. */
const RESERVED = new Set(['self', 'idempotency_key', 'timeout', 'max_retries', 'extra_headers'])

const pyIdent = (name: string) => (PY_KEYWORDS.has(name) ? `${name}_` : name)

/** `del` is a keyword in Python; everything else is the TS name in snake_case. */
function pyMethod(op: SpecOperation): string {
  return pyIdent(op.sdkMethod === 'del' ? 'delete' : snake(op.sdkMethod))
}

/** Same stem as the TS SDK's type names (InvoiceSend…), so both SDKs name inline shapes alike. */
function typeStem(op: SpecOperation): string {
  return op.resource.singular + pascal(op.sdkMethod === 'del' ? 'delete' : op.sdkMethod)
}

// ---------------------------------------------------------------------------
// 1. The schema set the models are generated from.
// ---------------------------------------------------------------------------

const schemas: Record<string, Json> = clone((raw.components as Json).schemas as Record<string, Json>)

/** The model each operation returns (or pages over), by name. */
const returnModel = new Map<string, string>()

for (const op of spec.operations) {
  const opRaw = ((raw.paths as Json)[op.path] as Json)[op.method.toLowerCase()] as Json
  const response = deref(raw, (opRaw.responses as Json)[String(op.successStatus)])
  const body = ((response.content as Json | undefined)?.['application/json'] as Json | undefined)?.schema
  if (op.kind === 'void' || op.kind === 'binary' || !body) continue
  const stem = typeStem(op)
  if (op.kind === 'body') {
    const name = refName(body) ?? `${stem}Response`
    if (!refName(body)) schemas[name] = clone(body as Json)
    returnModel.set(op.operationId, name)
    continue
  }
  if (op.dataRef) {
    returnModel.set(op.operationId, op.dataRef)
    continue
  }
  // Inline `data` (or inline page items): give it the same name the TS SDK uses.
  const data = deref(raw, deref(raw, body).properties && (deref(raw, body).properties as Json).data)
  const shape = op.kind === 'page' ? deref(raw, data.items) : data
  const name = `${stem}${op.kind === 'page' ? 'Item' : 'Result'}`
  schemas[name] = clone(shape)
  returnModel.set(op.operationId, name)
}

const isObjectSchema = (s: Json | undefined) => !!s && s.type === 'object' && typeof s.properties === 'object'

/** Moves inline objects into named schemas (`Customer.address` → `CustomerAddress`) so models get readable names. */
function hoist(): void {
  const visit = (node: Json, suggested: string): Json => {
    if (!node || typeof node !== 'object' || node.$ref) return node
    if (isObjectSchema(node)) {
      let name = suggested
      for (let i = 2; schemas[name] && schemas[name] !== node; i++) name = `${suggested}${i}`
      schemas[name] = node
      walk(name, node)
      const out: Json = { $ref: `#/components/schemas/${name}` }
      if (typeof node.description === 'string') out.description = node.description
      return out
    }
    for (const key of ['anyOf', 'oneOf', 'allOf'] as const) {
      if (Array.isArray(node[key])) node[key] = (node[key] as Json[]).map((m) => visit(m, suggested))
    }
    if (node.type === 'array' && node.items) node.items = visit(node.items as Json, `${suggested}Item`)
    return node
  }
  const walk = (name: string, schema: Json) => {
    const props = (schema.properties ?? {}) as Record<string, Json>
    for (const [prop, ps] of Object.entries(props)) props[prop] = visit(ps, name + pascalWords(prop))
  }
  for (const name of Object.keys(schemas)) walk(name, schemas[name]!)
}
hoist()

