// 3. Python types for request params.
// ---------------------------------------------------------------------------

const paramTypedDicts = new Set<string>()
/** While typing a method's keyword arguments, nested objects also accept the matching model. */
let acceptModels = false

function literal(v: unknown): string {
  if (typeof v === 'string') return JSON.stringify(v)
  if (typeof v === 'boolean') return v ? 'True' : 'False'
  if (v === null) return 'None'
  return String(v)
}

/**
 * The flat list of Python types a JSON Schema accepts on the request side
 * ('None' for null). Registers the TypedDicts it needs.
 */
function pyMembers(node: unknown, imports: Set<string>): string[] {
  const s = (node ?? {}) as Json
  const ref = refName(s)
  if (ref) {
    const target = schemas[ref]
    if (isObjectSchema(target)) {
      paramTypedDicts.add(ref)
      return acceptModels ? [`${ref}Param`, ref] : [`${ref}Param`]
    }
    return pyMembers(target, imports)
  }
  const union = (s.anyOf ?? s.oneOf) as Json[] | undefined
  if (union) {
    let members = [...new Set(union.flatMap((m) => pyMembers(m, imports)))]
    // `str | Literal[""]` is just `str`.
    if (members.includes('str')) members = members.filter((m) => !/^Literal\["/.test(m))
    return members
  }
  if (s.const !== undefined) {
    imports.add('Literal')
    return [`Literal[${literal(s.const)}]`]
  }
  if (Array.isArray(s.enum)) {
    imports.add('Literal')
    return [`Literal[${(s.enum as unknown[]).map(literal).join(', ')}]`]
  }
  switch (s.type) {
    case 'null':
      return ['None']
    case 'string':
      if (s.format === 'date' || s.format === 'date-time') {
        imports.add('datetime')
        return ['str', `datetime.${s.format === 'date' ? 'date' : 'datetime'}`]
      }
      return ['str']
    case 'integer':
      return ['int']
    case 'number':
      return ['float']
    case 'boolean':
      return ['bool']
    case 'array':
      imports.add('Sequence')
      return [`Sequence[${pyType(s.items, imports)}]`]
    case 'object':
      if (isObjectSchema(s)) throw new Error('sdk-gen: inline object in a request param should have been hoisted')
      imports.add('Dict')
      return ['Dict[str, object]']
    default:
      return ['object']
  }
}

/** One annotation from a member list, e.g. `Union[str, datetime.date]` or `Optional[str]`. */
function annotate(members: string[], imports: Set<string>): string {
  const nonNull = members.filter((m) => m !== 'None')
  const nullable = nonNull.length !== members.length
  if (nonNull.length === 0) return 'None'
  if (nonNull.length > 1) imports.add('Union')
  const t = nonNull.length === 1 ? nonNull[0]! : `Union[${nonNull.join(', ')}]`
  if (!nullable) return t
  imports.add('Optional')
  return `Optional[${t}]`
}

function pyType(node: unknown, imports: Set<string>): string {
  return annotate(pyMembers(node, imports), imports)
}

/** The annotation of an optional keyword argument: its types plus NotGiven. */
function optionalKwargType(node: unknown, imports: Set<string>): string {
  imports.add('Union')
  const members = pyMembers(node, imports)
  const nonNull = members.filter((m) => m !== 'None')
  return `Union[${[...nonNull, 'NotGiven', ...(nonNull.length !== members.length ? ['None'] : [])].join(', ')}]`
}

/** The typing names a block of generated code actually uses. */
function usedTyping(code: string, candidates: string[]): string[] {
  return candidates.filter((n) => new RegExp(`\\b${n}\\[`).test(code)).sort()
}

function oneLine(text: unknown): string {
  return String(text ?? '')
    .replace(/\s+/g, ' ')
    .trim()
}

function docEscape(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"')
}

function emitParams(): string {
  const imports = new Set<string>(['TypedDict'])
  const blocks: string[] = []
  const done = new Set<string>()
  // Registering a TypedDict can register more (nested refs), so loop until stable.
  for (;;) {
    const todo = [...paramTypedDicts].filter((n) => !done.has(n)).sort()
    if (!todo.length) break
    for (const name of todo) {
      done.add(name)
      const schema = schemas[name]!
      const required = new Set((schema.required as string[] | undefined) ?? [])
      const lines = [`class ${name}Param(TypedDict, total=False):`]
      const desc = oneLine(schema.description)
      lines.push(`    """${docEscape(desc || `The \`${name}\` object, as a request parameter.`)}"""`, '')
      for (const [prop, ps] of Object.entries(schema.properties as Record<string, Json>)) {
        if (PY_KEYWORDS.has(prop) || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(prop)) {
          throw new Error(`sdk-gen: ${name}.${prop} is not a valid TypedDict key in Python`)
        }
        let t = pyType(ps, imports)
        if (required.has(prop)) {
          imports.add('Required')
          t = `Required[${t}]`
        }
        const d = oneLine(ps.description ?? deref(raw, ps).description)
        if (d) lines.push(`    ${prop}: ${t}`, `    """${docEscape(d)}"""`, '')
        else lines.push(`    ${prop}: ${t}`, '')
      }
      blocks.push(lines.join('\n').trimEnd())
    }
  }
  const names = [...done].sort().map((n) => `${n}Param`)
  const code = blocks.join('\n')
  const typing = usedTyping(code, ['Dict', 'Optional', 'Sequence', 'Union'])
  const ext = [...usedTyping(code, ['Literal', 'Required']), 'TypedDict'].sort()
  if (!/\bdatetime\./.test(code)) imports.delete('datetime')
  return [
    HEADER,
    '"""TypedDicts for nested request objects: pass plain dicts shaped like these (or the matching models)."""',
    '',
    'from __future__ import annotations',
    '',
    ...(imports.has('datetime') ? ['import datetime'] : []),
    ...(typing.length ? [`from typing import ${typing.join(', ')}`] : []),
    ...(imports.has('datetime') || typing.length ? [''] : []),
    `from typing_extensions import ${ext.join(', ')}`,
    '',
    `__all__ = [${names.map((n) => JSON.stringify(n)).join(', ')}]`,
    '',
    '',
    blocks.join('\n\n\n'),
    '',
  ].join('\n')
}

